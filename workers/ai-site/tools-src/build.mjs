// Builds src/tools-widget.js from tools-src/ (widget markup, CSS and browser JS for the
// keyword-research and content-marketing tools). Run: node tools-src/build.mjs
import { transform } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL(".", import.meta.url);
const js = (await transform(readFileSync(new URL("widget-client.js", here), "utf8"), { loader: "js", minify: true, target: "es2017" })).code.trim();
const css = (await transform(readFileSync(new URL("widget.css", here), "utf8"), { loader: "css", minify: true })).code.trim();
const tpl = readFileSync(new URL("widget-template.js", here), "utf8");
writeFileSync(new URL("../src/tools-widget.js", here),
  "// GENERATED by tools-src/build.mjs — edit tools-src/* and rebuild.\n" +
  `const CLIENT_JS = ${JSON.stringify(js.replace(/<\/script/gi, "<\\/script"))};\n` +
  `const CLIENT_CSS = ${JSON.stringify(css + ".wdt-vh{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0 0 0 0)}")};\n` + tpl);
console.log("wrote src/tools-widget.js");
